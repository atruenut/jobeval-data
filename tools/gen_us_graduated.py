#!/usr/bin/env python3
"""Writes packs-src/US/<ST>.2026.yaml and tests-src/US-<ST>-2026.yaml for the bracketed state packs
from tools/us_graduated_data.py and tools/reference_us_graduated.py.   python3 tools/gen_us_graduated.py"""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from us_graduated_data import STATES
from reference_us_graduated import tax, CASES
from decimal import Decimal as D

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = ('tf_rates: { authority: third_party, title: "Tax Foundation: 2026 State Individual Income Tax Rates and Brackets '
       '(rates as of 1 Jan 2026)", url: "https://taxfoundation.org/data/all/state/state-income-tax-rates-2026/", retrieved: 2026-11-13 }')

def num(d):
    d = D(d); return format(d.normalize(), "f")

def table(starts):
    rows = []
    for i, (rate, s) in enumerate(starts):
        if i == 0 and s > 0: rows.append((s, D(0)))
        if i + 1 < len(starts): rows.append((starts[i + 1][1], rate))
        else: rows.append((None, rate))
    out = []
    for up, rate in rows:
        out.append("      - { up_to: %s, rate: %s }" % (num(up), num(rate)) if up is not None else "      - { rate: %s }" % num(rate))
    return "\n".join(out)

for code, s in STATES.items():
    lc = code.lower(); mfj = "mfj" in s
    params = []
    params.append(f"  {lc}.brackets_single:\n    source: tf_rates\n    value:\n{table(s['single'])}")
    if mfj: params.append(f"  {lc}.brackets_mfj:\n    source: tf_rates\n    value:\n{table(s['mfj'])}")
    for key, pk in (("std", "deduction"), ("exempt", "exemption"), ("credit", "credit")):
        if key in s: params.append(f"  {lc}.{pk}:\n    source: tf_rates\n    value: {{ single: {s[key][0]}, mfj: {s[key][1]} }}")
    def sel(kind):
        return f"if(filing_status == 2, $%s.%s.mfj, $%s.%s.single)" % (lc, kind, lc, kind)
    if s.get("fed"):
        base = "taxable_income"
    else:
        parts = [sel(k) for k in ("deduction", "exemption") if (k == "deduction" and "std" in s) or (k == "exemption" and "exempt" in s)]
        base = "max(0, agi - " + " - ".join(parts) + ")" if parts else "agi"
    bs = f"bracket({base}, $%s.brackets_single)" % lc
    bm = f"bracket({base}, $%s.brackets_mfj)" % lc if mfj else bs
    core = bs if not mfj else f"if(filing_status == 2, {bm}, {bs})"
    expr = f"max(0, {core} - {sel('credit')})" if "credit" in s else core
    note = ("Bracketed tax on " + ("federal taxable income" if s.get("fed") else "income less the state standard deduction and personal exemption where the state has them")
            + "; married filing jointly uses the joint amounts, head of household the single ones.")
    y = f"""# {s['name']}, state layer, tax year 2026. Extends US-2026. Generated by tools/gen_us_graduated.py from tools/us_graduated_data.py.
schema: 1
id: US-{code}-2026
kind: subregion
extends: US-2026
region: {{ country: US, subregion: {code} }}
valid: {{ from: 2026-01-01, to: 2026-12-31 }}
revision: 1
tier: {s['tier']}
requires_engine: ">=1.1"
labels: {{ en: "{s['name']} (2026)", fr: "{s['fr']} (2026)" }}

sources:
  {SRC}

parameters:
""" + "\n".join(params) + f"""

rules:
  - id: {lc}.tax
    label: {{ en: "{s['name']} income tax" }}
    note: "{note}"
    expr: {expr}

append:
  income_tax: [{lc}.tax]

not_modelled:
""" + "".join(f"  - {x}\n" for x in s["nm"] + ["state_unemployment_benefit", "state_overtime_rules"])
    open(f"{ROOT}/packs-src/US/{code}.2026.yaml", "w").write(y)
    cases = ""
    for g, st in CASES:
        cases += f"  - id: {lc}-tax-{g}-fs{st}\n    status: derived\n    inputs: {{ gross_annual: {g}, filing_status: {st}, as_of: 2026-11-13 }}\n    expect: {{ {lc}.tax: {tax(code, g, st).quantize(D('0.001'))} }}\n"
    open(f"{ROOT}/tests-src/US-{code}-2026.yaml", "w").write(f"""# Golden tests for US-{code}-2026 (generated).
# status derived: tools/reference_us_graduated.py (own arithmetic from the cited figures; not an official run).
suite: US-{code}-2026
pack: US-{code}-2026
tolerance: {{ abs: 0.01 }}
cases:
{cases}""")
print("wrote", len(STATES))
